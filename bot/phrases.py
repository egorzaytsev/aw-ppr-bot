"""Живые реплики бота: варианты фраз, немного испанского кириллицей.

Только подача: подтверждения, приветствия, вступления. Статусы, сроки и решения
формулируются строго и сюда не попадают.

Голос бота — Пепе (уменьшительное от Хосе; на сленге ещё и «деньги»): к дилеру на «ты»
и без указания рода дилера, о себе — в мужском роде («записал», «получил»).
Иногда упоминает Егора: «посмотрим, что скажет Егор».
"""
from __future__ import annotations

import random

# Короткая реакция на ответ перед следующим вопросом
ACKS = (
    "Перфекто!", "Хениаль!", "Буэно!", "Кларо!", "Записал.", "Отлично.", "Принято.", "Есть.",
    "Муй бьен!", "Вамос дальше!",
)
# Перед итогом «информацию получили»
THANKS = ("Мучас грасиас!", "Грасиас!", "Перфекто, спасибо!", "Спасибо!", "Хениаль, спасибо!")
# Приветствие по имени
HELLO = ("Ола", "Привет", "Ола")
# Файл или ссылка приняты
GOT_FILE = ("Получил!", "Перфекто, есть.", "Принято.", "Буэно, получил.")
# Вступление к напоминанию
REMINDER_INTRO = (
    "Ола! Небольшая сверка по твоим плейсментам.",
    "Ола! Напоминание по твоим плейсментам.",
    "Ола! Сверим проекты.",
    "Ола! Пара моментов по твоим плейсментам.",
    "Ола! Егор просил сверить проекты.",
)
# Иногда — про Егора (после отправки заявки)
EGOR = (
    "Передал Егору — посмотрим, что скажет.",
    "Посмотрим, что скажет Егор.",
    "Егор посмотрит и вернётся с ответом.",
)
EGOR_CHANCE = 0.5

# Конец близко
LAST_STEPS = {1: "Последний вопрос — и готово.", 2: "Ещё два вопроса — и готово."}

ACK_CHANCE = 0.5  # реакция не на каждый ответ — иначе приедается

_last: dict = {}
_rng = random.Random()


def pick(options: tuple, key: str | None = None) -> str:
    """Случайный вариант, не повторяя предыдущий для того же набора."""
    key = key or options[0]
    choices = [o for o in options if o != _last.get(key)] or list(options)
    choice = _rng.choice(choices)
    _last[key] = choice
    return choice


def maybe_ack() -> str | None:
    return pick(ACKS, "ack") if _rng.random() < ACK_CHANCE else None


def maybe_egor() -> str | None:
    return pick(EGOR, "egor") if _rng.random() < EGOR_CHANCE else None


def first_name(full_name: str) -> str:
    name = (full_name or "").split("(")[0].strip()
    return name.split()[0] if name else ""


def seed(value: int) -> None:
    """Для тестов: предсказуемый выбор."""
    _rng.seed(value)
    _last.clear()
